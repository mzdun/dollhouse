"""
Step for the Python dynamic modules built by CMake: ``DynModulesInstall``
copies the binaries and their stubs into the site-packages of the interpreter
running Flow. The stubs are generated by pybind11-stubgen as a post-build step
of each module (see ``.flow/cmake/genstubs.cmake``).

Configuration (``.flow/config.yml``) names the modules:

.. code-block:: yaml

    python-dynamic-modules:
      - shapes

Each module is looked up in ``<build dir>/bin`` as either one of::

    NAME.<tag>.pyd            NAME/__init__.<tag>.pyd

where ``<tag>`` is the OS/ABI part, e.g. ``cp312-win_amd64``; its stubs,
as either one of::

    NAME.pyi                  NAME/**/*.pyi
"""

import sysconfig
from pathlib import Path

from proj_flow.api import env, step

EXTENSIONS = ["pyd", "so"]


def _modules(rt: env.Runtime) -> list[str]:
    return [str(name) for name in rt._cfg.get("python-dynamic-modules", [])]


def _bin_dir(config: env.Config) -> Path:
    return (config.build_dir / "bin").absolute()


def _site_packages() -> Path:
    return Path(sysconfig.get_path("platlib"))


def _locate_binaries(bin_dir: Path, module: str) -> list[Path]:
    """Paths, relative to bin_dir, of every built variant of the module."""
    patterns = [
        "{module}.*.{ext}",
        "{module}/__init__.*.{ext}",
    ]
    found = set[Path]()
    for pattern in patterns:
        for ext in EXTENSIONS:
            for path in bin_dir.glob(pattern.format(module=module, ext=ext)):
                found.add(path.relative_to(bin_dir))
    return sorted(found)


def _locate_stubs(root: Path, module: str) -> list[Path]:
    """Stubs of the module under root: ``<module>.pyi`` and
    ``<module>/**/*.pyi``."""
    result = list[Path]()
    file_name = root / f"{module}.pyi"
    dir_name = root / module

    if file_name.is_file():
        result.append(file_name)

    if dir_name.is_dir():
        result.extend(
            sorted(path for path in dir_name.rglob("*.pyi") if path.is_file())
        )

    return result


def _remove_stubs(rt: env.Runtime, root: Path, module: str):
    """Removes the stubs of the module from root, so the stubs of removed
    submodules do not linger."""
    for stub in _locate_stubs(root, module):
        rt.print("rm", str(stub))
        if not rt.dry_run:
            stub.unlink()


def _locate_installed_binaries(root: Path, module: str) -> list[Path]:
    """Every binary of the module under root, including the versioned ones
    (``….so.0.1``) left by older builds, and broken symlinks."""
    patterns = [
        "{module}.*.{ext}",
        "{module}.*.{ext}.*",
        "{module}/__init__.*.{ext}",
        "{module}/__init__.*.{ext}.*",
    ]
    found = set[Path]()
    for pattern in patterns:
        for ext in EXTENSIONS:
            for path in root.glob(pattern.format(module=module, ext=ext)):
                if path.is_file() or path.is_symlink():
                    found.add(path)
    return sorted(found)


def _remove_binaries(rt: env.Runtime, root: Path, module: str):
    """Removes the binaries of the module from root, so the binaries of
    other versions, or other ABI tags, do not linger."""
    for path in _locate_installed_binaries(root, module):
        rt.print("rm", str(path))
        if rt.dry_run:
            continue
        try:
            path.unlink()
        except PermissionError:
            rt.fatal(
                f"dyn-modules-install: {path} is in use; "
                "close the Python processes using it"
            )


@step.register
class DynModulesInstallStep:
    """
    Copies the configured Python dynamic modules, and their stubs made by
    the build, to the site-packages of the current interpreter.
    """

    name = "DynModulesInstall"
    runs_after = ["Build"]

    def is_active(self, config: env.Config, rt: env.Runtime) -> bool:
        return len(_modules(rt)) > 0

    def run(self, config: env.Config, rt: env.Runtime) -> int:
        if config.items.get("sanitizer"):
            rt.fatal(
                "dyn-modules-install: a sanitizer build cannot be loaded by a "
                "plain interpreter; use `./flow test --sane`, or install "
                "a build without sanitizers"
            )

        site_packages = _site_packages()
        bin_dir = _bin_dir(config)

        for module in _modules(rt):
            files = _locate_binaries(bin_dir, module)
            if not files and not rt.dry_run:
                rt.fatal(
                    f"dyn-modules-install: `{module}` not found in {bin_dir}",
                )

            stubs = _locate_stubs(bin_dir, module)
            if not stubs and not rt.dry_run:
                rt.fatal(
                    f"dyn-modules-install: no stubs of `{module}` in {bin_dir}; "
                    "is pybind11-stubgen installed?",
                )

            _remove_binaries(rt, site_packages, module)
            for dll in files:
                dst_dir = (site_packages / dll).parent
                result = rt.mkdirs(str(dst_dir))
                if result:
                    return result
                result = rt.cp(str(bin_dir / dll), str(dst_dir))
                if result:
                    return result

            _remove_stubs(rt, site_packages, module)
            for stub in stubs:
                dst = site_packages / stub.relative_to(bin_dir)
                result = rt.mkdirs(str(dst.parent))
                if result:
                    return result
                result = rt.cp(str(stub), str(dst))
                if result:
                    return result

        return 0
